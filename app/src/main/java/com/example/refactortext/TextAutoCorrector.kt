    private val allMaps = listOf(
        colloquialMap,
        prepositionMap,
        spellingMap,
        phoneticMap,
        normalizeMap
    )

    /**
     * Применяет все словари и правил к тексту.
     * Работает локально, без сети.
     */
    fun correctText(text: String): String {
        if (text.isBlank()) return text

        var result = text

        // 1. Применяем все словари по очереди
        for (map in allMaps) {
            map.forEach { (wrong, correct) ->
                if (correct.isEmpty()) {
                    // Удаляем слово целиком (например, мат)
                    val regex = Regex("(?i)\\b${Regex.escape(wrong)}\\b")
                    result = regex.replace(result, "")
                } else {
                    val regex = Regex("(?i)\\b${Regex.escape(wrong)}\\b")
                    result = regex.replace(result) { match ->
                        preserveCase(match.value, correct)
                    }
                }
            }
        }

        // 2. Нормализация пробелов и знаков
        result = result
            .replace(Regex("\\s+"), " ")    // схлопываем множественные пробелы
            .replace(Regex("\\s*,\\s*"), ", ") // нормализуем запятые
            .replace(Regex("\\s*\\.\\s*"), ". ") // нормализуем точки
            .trim()
            .removeSuffix(",")
            .removeSuffix(".")
            .trim()

        if (result != text) {
            Log.d(TAG, "Автокоррекция: \"$text\" → \"$result\"")
        }

        return result
    }

    /**
     * Сохраняет регистр первой буквы как в оригинале.
     */
    private fun preserveCase(original: String, replacement: String): String {
        return if (original.isNotEmpty() && replacement.isNotEmpty()) {
            if (original.first().isUpperCase()) {
                replacement.replaceFirstChar { it.uppercase() }
            } else {
                replacement
            }
        } else {
            replacement
        }
    }
